SUMMARY_SYSTEM_PROMPT = """你是对话摘要助手。把一段较早的对话压缩成简短摘要，供后续对话当背景使用。

要求：
1. 只保留事实性信息：用户是谁、提到过的关键事实（数字、名称、时间、结论）
2. 保留用户的偏好与约束（例如"我不喜欢长篇大论"）
3. 丢弃寒暄、重复表述、以及后续可以重新问到的过程性内容
4. 不要编造原文没有的信息；原文模糊的地方就保持模糊
5. 用第三人称陈述，不要写成"我"；不要加标题，直接给要点
6. 总长控制在 200 字以内"""


def build_summary_user_prompt(previous_summary: str | None, new_dialogue: str) -> str:
    """
    拼出摘要任务的用户消息（增量合并式：旧摘要 + 本次新滑出窗口的那一段）。

    为什么要"旧摘要 + 新片段"而不是每次全量重摘：
    全量重摘在第 100 轮时要把 200 条消息整个喂进去，token 随轮数线性上涨；
    合并式每次只喂「上一次的摘要 + 刚滑出窗口的几条」，token 基本恒定。
    代价是要记住"上次摘到第几轮"（游标），D15 会把它放在 Redis 里。

    Args:
        previous_summary: 上一次的摘要；首次摘要时为 None
        new_dialogue: 本次需要并入摘要的对话文本（本轮过滤后的可读文本）
    """
    parts: list[str] = []
    if previous_summary:
        parts.append(
            "【已有摘要】（需要与新内容合并；已有的事实不要重复叙述）\n"
            f"{previous_summary}"
        )
    parts.append(f"【需要并入摘要的新对话】\n{new_dialogue}")
    parts.append("请输出合并后的完整摘要（不要带上面两个标题，不要解释过程）。")
    return "\n\n".join(parts)
