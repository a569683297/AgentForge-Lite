"""
画像抽取 prompt（2026-10-21）
=============================
从"用户最近说过的话"里抽出**跨会话仍然成立**的稳定信息。

为什么这段 prompt 要如此强调"不要抽什么"
------------------------------------------
抽取器的失败模式不是"抽不到"，而是**抽得太多**：
  · 把"帮我改一下这段代码"抽成 "用户正在修改代码" —— 一句一次性的任务冒充长期事实
  · 把助手说过的话抽成用户的属性 —— 用户从没这么说过
  · 把上下文里的猜测写成事实 —— "用户可能在北京"

前两类会污染注入、浪费 top-k 配额；第三类更糟：用户会在画像页看到一条
自己从没说过的话，然后不再信任这个功能。**宁可少抽，不可抽错。**

所以 prompt 里"绝对不要提取"那一段比"要提取什么"更长。这不是话痨，
是对失败模式的正面处置 —— 只写"提取稳定信息"，模型会倾向于多抽（多抽看起来更努力）。

为什么只喂用户的消息、不喂助手的话
----------------------------------
① 助手说的话**不是证据**：它是模型生成的，可能是幻觉；把它当画像来源，
   等于让模型给自己的幻觉盖章。
② 省 token：一轮对话里助手的话通常比用户长得多（带格式、带代码）。
③ 语义更干净：用户问"这个报错怎么修"不会污染抽取（本来就不该抽），
   但助手答的一大段技术细节如果不小心被抽成"用户熟悉 X"，那就错了。
代价是某些指代（"对，就是这个意思"）脱离上下文看不懂 —— 但这类内容本来就不该被抽。
"""

EXTRACT_SYSTEM_PROMPT = """你是一个"用户画像提取器"。任务：从用户说过的话里，挑出**跨会话仍然成立**的、关于用户本人的稳定信息。

只提取这三类：
- fact：关于用户的客观事实（职业、所在城市、在做的项目、技术栈、常用语言、工作方式）
- preference：用户的偏好（喜欢/讨厌什么、习惯怎么做、希望被怎么对待、明确说过的要求）
- goal：用户正在推进的目标（准备面试、要上线某个功能、正在学习某样东西）

**绝对不要提取**（这几条比上面更重要）：
1. 一次性的任务或问题。"帮我改这段代码"、"这个报错什么意思"都不是画像。
2. 助手说过的内容。只以**用户自己说的**为准。
3. 上下文里的推测。用户没明说的，一律不抽。
4. 敏感信息：证件号、密码、密钥、详细住址、健康状况、财务状况 —— 用户明说了也不要。
5. 已经出现在【已有画像】里的内容（不要重复）。

判断标准：假设这个人下周开一个全新的对话，这条信息还成立吗？不成立就不要抽。

输出格式：**严格的 JSON 数组**，不要解释、不要 markdown 代码块、不要前后缀文字。
每个元素形如：
{"kind": "fact|preference|goal", "text": "一句话，20 字以内，第三人称陈述", "confidence": 0.0到1.0}

text 要求：陈述句、不加主语"用户"、不带句末标点。例如「偏好 TypeScript 而不是 JavaScript」。
没有可提取的内容时，**只输出** []"""


def build_extract_user_prompt(dialogue: str, existing: list[str] | None = None) -> str:
    """
    拼抽取任务的用户消息。

    Args:
        dialogue: 用户最近说过的话（时间正序，一行一条，已带序号）
        existing: 已有的事实文本（用来让模型避开重复）

    为什么把"已有画像"也喂进去（而不是只靠数据库唯一约束去重）：
      约束只能拦住**字面相同**的重复。模型换个说法（"偏好 TS" vs "喜欢用 TypeScript"）
      就绕过去了 —— 而 top-k 只有 4 个配额，被同义重复占满等于画像失效。
      把已有内容给它看，是让它在**生成阶段**就避开，比事后去重更省。
      ⚠ 但约束仍然必须在：模型不听话时，它是最后一道闸。
    """
    parts: list[str] = []
    if existing:
        lines = "\n".join(f"- {text}" for text in existing)
        parts.append(f"【已有画像】（不要重复提取这些）\n{lines}")
    parts.append(f"【用户最近说过的话】\n{dialogue}")
    parts.append("请按系统提示的格式输出 JSON 数组。")
    return "\n\n".join(parts)
